  <h2>第1条（目的）</h2><p>本規約は、本サイトが提供する求人情報の掲載・閲覧・応募の各サービス（以下「本サービス」）の利用条件を定めるものです。</p>
  <h2>第2条（求人情報）</h2><p>掲載する求人情報は、職業安定法その他の法令に従い、正確かつ最新の内容に保つものとします。虚偽・誤解を招く表示、法令に反する募集（年齢・性別による不当な制限を含む）が判明した場合、運営者は掲載を停止できます。</p>
  <h2>第3条（応募）</h2><p>応募情報は、応募先の企業と運営者に提供されます。採用の可否・労働条件は応募者と企業の間で決定され、運営者は雇用契約の当事者とはなりません。</p>
  <h2>第4条（禁止事項）</h2><p>虚偽の情報の登録、他人へのなりすまし、本サービスの運営を妨げる行為、その他運営者が不適切と判断する行為を禁止します。</p>
  <h2>第5条（苦情・お問い合わせ）</h2><p>本サービスに関する苦情・お問い合わせは、運営者情報に記載の連絡先で受け付け、適切かつ速やかに対応します。</p>
  <h2>第6条（免責・変更）</h2><p>運営者は、本サービスの内容を予告なく変更・停止することがあります。本規約は必要に応じて改定し、本サイトに掲載した時点から効力を生じます。</p>
